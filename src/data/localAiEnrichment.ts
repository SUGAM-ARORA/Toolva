/**
 * Normalizes tool name to look up in the enrichment presets.
 */
export function getEnrichmentKey(name: string): string {
  if (!name) return '';
  const clean = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (clean.includes('ollama')) return 'ollama';
  if (clean.includes('llamacpp') || clean.includes('ggml')) return 'llamacpp';
  if (clean.includes('vllm')) return 'vllm';
  if (clean.includes('lmstudio')) return 'lmstudio';
  if (clean.includes('comfyui')) return 'comfyui';
  if (clean.includes('whispercpp')) return 'whispercpp';
  if (clean.includes('jan') && !clean.includes('janitor')) return 'jan';
  if (clean.includes('openwebui')) return 'openwebui';
  if (clean.includes('anythingllm')) return 'anythingllm';
  if (clean.includes('continuedev') || clean.includes('continue')) return 'continuedev';
  if (clean.includes('aider')) return 'aider';
  return '';
}

/**
 * Enhances a given AITool with rich local AI specifications if it matches a preset.
 */
export function enrichAITool(tool: AITool): AITool {
  const key = getEnrichmentKey(tool.name);
  if (!key || !LOCAL_AI_ENRICHMENT_CATALOG[key]) {
    // If not matching a local preset, ensure basic Bayesian score defaults are set
    if (!tool.bayesianScore) {
      tool.bayesianScore = Math.round((0.7 * (tool.rating || 4.2) + 0.3 * 4.20) * 100) / 100;
      tool.reviewCount = tool.reviewCount || 15;
      tool.sampleConfidence = 'moderate';
    }
    return tool;
  }

  const preset = LOCAL_AI_ENRICHMENT_CATALOG[key];
  return {
    ...tool,
    ...preset,
    // Preserve tool id and existing dynamic properties
    id: tool.id,
    name: preset.name || tool.name,
    description: preset.description || tool.description,
  };
}
